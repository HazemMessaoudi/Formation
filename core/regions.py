"""الجهات المرجعيّة — الولايات والإدارات الجهويّة ووحدات الحرس الدّيواني.

لماذا هذه الوحدة
================
كلّ مكوّن وكلّ مشارك ينتمي إلى جهة: إدارة جهويّة للدّيوانة، أو وحدة من
وحدات الحرس الدّيواني. قبل الإصدار 58 كانت هذه القيم تُكتب باليد في كلّ
مرّة، فيقع الاسم الواحد في القائمة بأربع صيغ مختلفة («الادارة الجهوية
بالقصرين»، «الإدارة الجهويّة للدّيوانة بالقصرين»…) ويصبح فرز المشاركين
حسب جهتهم مستحيلا.

القاعدة الحاكمة
===============
لا تُولَّد قواعد النّحو العربي داخل الشّيفرة — وهي القاعدة نفسها المعتمدة
في `core/identite.py`. لذلك تُخزَّن لكلّ ولاية صيغتان محفوظتان حرفا بحرف:
الاسم المجرّد («بنزرت») والاسم مسبوقا بحرف الجرّ («ببنزرت»). أيّ اشتقاق
آلي يُخطئ حتما: «بنزرت» تعطي «ببنزرت» لا «بنزرت»، و«الكاف» تعطي «بالكاف»
لا «بالكاف» بزيادة همزة.

ما تقترحه الوحدة وما لا تقترحه
===============================
  • الولايات الأربع والعشرون: قائمة مغلقة ومعروفة، تُعطى كاملة.
  • الإدارات الجهويّة: تُقترح واحدة لكلّ ولاية بصيغة موحّدة. وهي
    اقتراحات لتوحيد الكتابة لا تنظيم إداري رسمي، ولكلّ مركز أن يضيف
    ما يخصّه أو يحذف ما لا يعنيه.
  • وحدات الحرس الدّيواني: لا تُقترح قائمة جاهزة. عددها وتوزيعها
    يختلفان من جهة إلى أخرى، واختراع قائمة أدقّ ضررا من تركها فارغة:
    يضيف كلّ مركز وحداته بنفسه، وتُغرس وحدته المرجعيّة تلقائيّا من
    جواب معالج التّنصيب.

الوحدة لا تستورد أيّ وحدة أخرى من المشروع.
"""

