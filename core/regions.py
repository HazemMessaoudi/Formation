NB_GOUVERNORATS = len(GOUVERNORATS)


def noms_gouvernorats():
    """الأسماء المجرّدة للولايات، مرتّبة كما هو متعارف عليه إداريّا."""
    return [nom for nom, _ba in GOUVERNORATS]


def avec_ba(nom):
    """الاسم مسبوقا بحرف الجرّ، أو الاسم كما هو إن لم يكن ولاية معروفة.

    لا يُشتقّ حرف الجرّ أبدا: إمّا أن يكون محفوظا وإمّا أن يُترك الاسم
    على حاله، لأنّ نصّا صحيحا ناقصا خير من نصّ مولَّد خاطئ.
    """
    cible = (nom or '').strip()
    for n, ba in GOUVERNORATS:
        if n == cible:
            return ba
    return cible


def est_gouvernorat(nom):
    return (nom or '').strip() in {n for n, _ in GOUVERNORATS}


