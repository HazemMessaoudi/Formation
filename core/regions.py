# ─── الغرس الأوّل ─────────────────────────────────────────────────────────────

def jihat_a_semer(config=None):
    """القيم التي تُغرس في جدول `jihat` عند التّنصيب أو التّرقية.

    تُضاف إليها الجهتان اللّتان صرّح بهما المركز في معالج التّنصيب
    (`admin_regionale` و `unite_garde`) إن لم تكونا في القائمة، حتّى
    يجد المستعمل جهته الخاصّة حاضرة من أوّل استعمال.
    """
    couples = [(nom, TYPE_ADMIN) for nom in administrations_regionales()]

    cfg = config or {}
    propre_admin = str(cfg.get('admin_regionale') or '').strip()
    if propre_admin and propre_admin not in administrations_regionales():
        couples.append((propre_admin, TYPE_ADMIN))

    propre_garde = str(cfg.get('unite_garde') or '').strip()
    if propre_garde:
        couples.append((propre_garde, TYPE_GARDE))

    return couples
