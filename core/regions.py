    """اقتراح إدارة جهويّة لكلّ ولاية، بصيغة كتابة موحّدة.

    التّركيب هنا ليس توليدا نحويّا: الجزآن محفوظان حرفا بحرف
    (`PREFIXE_ADMIN` و صيغة الجرّ من الجدول أعلاه) ولا يُبنى منهما
    إلّا الوصل بمسافة.
    """
    return [f'{PREFIXE_ADMIN} {ba}' for _nom, ba in GOUVERNORATS]


