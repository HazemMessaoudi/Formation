_INDEX = {f['id']: f for f in FICHES}
_PAGES = {ep: f['id'] for f in FICHES for ep in f['pages']}


def fiche(ident):
    return _INDEX.get(ident)


def fiche_pour(endpoint):
    """Identifiant de la fiche du bouton « ؟ » pour cette page ('' : sommaire)."""
    return _PAGES.get(endpoint or '', '')


def sommaire():
    """[(partie, numéro, titre, [fiches])] dans l'ordre du دليل."""
    return [(p, n, t, [f for f in FICHES if f['partie'] == p]) for p, n, t in PARTIES]


def texte_recherche(f):
    """Texte indexé par la recherche de la page (titre, but, étapes, remarques)."""
    return ' '.join([f['titre'], f['but'], *f['etapes'], *f['notes']])
